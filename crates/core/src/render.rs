//! Every renderer: the model plus the repository, service and cache layers
//! (spec: 模型 / 仓储契约 / 服务契约 / 缓存契约). `table` is this module's
//! interface: it decides what one table yields, including its warnings and its
//! third-party dependencies. Every fact comes from the resolved table; the
//! renderers below only format text.

use crate::generate::{Dialect, FileKind, GeneratedFile, GenerateRequest};
use crate::resolve::Table;

mod contract;

use contract::{Contract, Method};

const GORM: &str = "gorm.io/gorm";
const REDIS: &str = "github.com/redis/go-redis/v9";

/// What one table contributes to the project.
pub(crate) struct TableOutput {
    pub(crate) files: Vec<GeneratedFile>,
    /// Final warning text: prefixed with the table name, or self-describing.
    pub(crate) warnings: Vec<String>,
    /// Third-party modules the emitted files import, deduplicated, in
    /// declaration order.
    pub(crate) dependencies: Vec<&'static str>,
}

/// Decides what one table produces. Tables without a primary key only get a
/// model, plus a warning; their repository/service/cache are not generated.
pub(crate) fn table(table: &Table, request: &GenerateRequest) -> TableOutput {
    let mut output = TableOutput {
        files: vec![model(table)],
        warnings: table
            .warnings
            .iter()
            .map(|warning| format!("{}: {}", table.sql_name, warning))
            .collect(),
        dependencies: Vec::new(),
    };
    if table.imports.gorm {
        push_dependency(&mut output.dependencies, GORM);
    }
    if !table.has_layers() {
        output.warnings.push(format!(
            "table `{}` has no primary key; only the model was generated",
            table.sql_name
        ));
        return output;
    }
    output.files.push(repository(table, request));
    output.files.push(service(table, request));
    push_dependency(&mut output.dependencies, GORM);
    if request.cache_enabled {
        output.files.push(cache(table, request));
        push_dependency(&mut output.dependencies, REDIS);
    }
    output
}

fn push_dependency(dependencies: &mut Vec<&'static str>, dependency: &'static str) {
    if !dependencies.contains(&dependency) {
        dependencies.push(dependency);
    }
}

/// Renders `internal/model/<table>.go`. Formatting only: every fact comes from
/// the resolved table.
fn model(table: &Table) -> GeneratedFile {
    let mut body = String::new();

    for (index, col) in table.columns.iter().enumerate() {
        let is_pk = table.pk_indices.contains(&index);
        let mut gorm_parts = vec![format!("column:{}", col.sql_name)];
        if is_pk {
            gorm_parts.push("primaryKey".to_string());
        }
        if col.auto_increment {
            gorm_parts.push("autoIncrement".to_string());
        }
        if col.generated {
            gorm_parts.push("->".to_string());
        }
        if !col.nullable {
            gorm_parts.push("not null".to_string());
        }
        let gorm_tag = gorm_parts.join(";");

        // Spec: DDL comments are preserved as Go comments, verbatim. Line
        // comment (`//`) cannot span lines, so newlines collapse to spaces.
        if let Some(comment) = &col.comment {
            body.push_str(&format!("\t// {}\n", comment.replace(['\n', '\r'], " ")));
        }
        body.push_str(&format!(
            "\t{field} {go_type} `gorm:\"{gorm_tag}\" json:\"{json}\"`\n",
            field = col.go_name,
            go_type = col.go_type,
            json = col.sql_name,
        ));
    }

    // Import block order is part of the golden output: json, gorm, time.
    let mut import_names: Vec<&str> = Vec::new();
    if table.imports.json {
        import_names.push("\"encoding/json\"");
    }
    if table.imports.gorm {
        import_names.push("\"gorm.io/gorm\"");
    }
    if table.imports.time {
        import_names.push("\"time\"");
    }
    let imports = match import_names.len() {
        0 => String::new(),
        1 => format!("import {}\n\n", import_names[0]),
        _ => format!(
            "import (\n{}\n)\n\n",
            import_names
                .iter()
                .map(|i| format!("\t{i}"))
                .collect::<Vec<_>>()
                .join("\n")
        ),
    };

    let table_comment = table
        .comment
        .as_ref()
        .map(|c| format!("// {}\n", c.replace(['\n', '\r'], " ")))
        .unwrap_or_default();

    let content = format!(
        "// Code generated by gorm-generate. DO NOT EDIT.\n\npackage model\n\n{imports}{table_comment}type {struct_name} struct {{\n{body}}}\n\nfunc ({recv} {struct_name}) TableName() string {{\n\treturn \"{table}\"\n}}\n",
        imports = imports,
        table_comment = table_comment,
        recv = table.struct_name.chars().next().map(|c| c.to_ascii_lowercase()).unwrap_or('x'),
        struct_name = table.struct_name,
        table = table.sql_name,
    );

    GeneratedFile {
        // File follows the struct name's singular form: users -> user.go.
        path: format!("internal/model/{}.go", table.file_base),
        content,
        table: table.sql_name.clone(),
        kind: FileKind::Model,
    }
}

/// Renders `internal/repository/<table>_repo.go`: interface, GORM impl, and
/// constructor in one file. Only called for tables with a primary key.
fn repository(table: &Table, request: &GenerateRequest) -> GeneratedFile {
    let contract = Contract::new(table);
    let where_chain = where_chain(table, request.dialect);
    // Only the PK parameter types appear in this file, so their import needs
    // are narrower than the model's field types.
    let pk_imports = table.pk_imports();
    let type_imports = if pk_imports.time { "\t\"time\"\n" } else { "" };
    let json_import = if pk_imports.json { "\t\"encoding/json\"\n" } else { "" };
    let content = format!(
        r#"// Code generated by gorm-generate. DO NOT EDIT.

package repository

import (
	"context"
	"fmt"
{type_imports}{json_import}
	"gorm.io/gorm"

	"{module}/internal/model"
)

// {repo_iface} is the persistence boundary for the {table} table.
type {repo_iface} interface {{
{interface}
}}

// {impl_type} implements {repo_iface} with GORM.
type {impl_type} struct {{
	db *gorm.DB
}}

// New{fn}Repository builds the GORM-backed implementation.
func New{fn}Repository(db *gorm.DB) {repo_iface} {{
	return &{impl_type}{{db: db}}
}}

func (r *{impl_type}) {create} {{
	return r.db.WithContext(ctx).Create(m).Error
}}

func (r *{impl_type}) {get_by_id} {{
	var m {s}
	err := r.db.WithContext(ctx).Where("{where_chain}", {where_args}).First(&m).Error
	if err != nil {{
		return nil, err
	}}
	return &m, nil
}}

func (r *{impl_type}) {list} {{
	if page < 1 || pageSize < 1 || page - 1 > int(^uint(0) >> 1) / pageSize {{
		return nil, 0, fmt.Errorf("page and pageSize must be positive and offset must fit int")
	}}
	var total int64
	if err := r.db.WithContext(ctx).Model(&{s}{{}}).Count(&total).Error; err != nil {{
		return nil, 0, err
	}}
	var items []*{s}
	offset := (page - 1) * pageSize
	err := r.db.WithContext(ctx).Order("{order}").Offset(offset).Limit(pageSize).Find(&items).Error
	return items, total, err
}}

func (r *{impl_type}) {update} {{
	return r.db.WithContext(ctx).Save(m).Error
}}

func (r *{impl_type}) {delete} {{
	return r.db.WithContext(ctx).Where("{where_chain}", {where_args}).Delete(&{s}{{}}).Error
}}
"#,
        type_imports = type_imports,
        json_import = json_import,
        module = request.module_path,
        table = table.sql_name,
        s = contract.model_type(),
        interface = contract.interface(),
        create = contract.signature(Method::Create),
        get_by_id = contract.signature(Method::GetByID),
        list = contract.signature(Method::List),
        update = contract.signature(Method::Update),
        delete = contract.signature(Method::Delete),
        where_chain = where_chain,
        where_args = contract.get_args(),
        order = go_string_literal(
            &table
                .pk()
                .map(|p| quote_sql(&p.sql_name, request.dialect))
                .collect::<Vec<_>>()
                .join(","),
        ),
        repo_iface = format!("{}Repository", table.struct_name),
        impl_type = impl_type(table, "Repository"),
        fn = table.struct_name,
    );

    GeneratedFile {
        path: format!("internal/repository/{}_repo.go", table.file_base),
        content,
        table: table.sql_name.clone(),
        kind: FileKind::Repository,
    }
}

/// Renders `internal/service/<table>_service.go`: interface, thin passthrough
/// impl, and constructor injecting the repository interface.
fn service(table: &Table, request: &GenerateRequest) -> GeneratedFile {
    let contract = Contract::new(table);
    let pk_imports = table.pk_imports();
    let type_imports = if pk_imports.time { "\t\"time\"\n" } else { "" };
    let json_import = if pk_imports.json { "\t\"encoding/json\"\n" } else { "" };
    let content = format!(
        r#"// Code generated by gorm-generate. DO NOT EDIT.

package service

import (
	"context"
{type_imports}{json_import}
	"{module}/internal/model"
	"{module}/internal/repository"
)

// {svc_iface} is the business-layer boundary for the {table} table. Fill in
// real business rules; the generated methods are thin passthroughs.
type {svc_iface} interface {{
{interface}
}}

type {impl_type} struct {{
	repo repository.{repo_iface}
}}

// New{fn}Service injects the repository interface; wire either the plain
// GORM repo or a cache decorator at the callsite.
func New{fn}Service(repo repository.{repo_iface}) {svc_iface} {{
	return &{impl_type}{{repo: repo}}
}}

func (s *{impl_type}) {create} {{
	return s.repo.Create(ctx, m)
}}

func (s *{impl_type}) {get_by_id} {{
	return s.repo.GetByID({forward_args})
}}

func (s *{impl_type}) {list} {{
	return s.repo.List(ctx, page, pageSize)
}}

func (s *{impl_type}) {update} {{
	return s.repo.Update(ctx, m)
}}

func (s *{impl_type}) {delete} {{
	return s.repo.Delete({forward_args})
}}
"#,
        type_imports = type_imports,
        json_import = json_import,
        module = request.module_path,
        table = table.sql_name,
        interface = contract.interface(),
        create = contract.signature(Method::Create),
        get_by_id = contract.signature(Method::GetByID),
        list = contract.signature(Method::List),
        update = contract.signature(Method::Update),
        delete = contract.signature(Method::Delete),
        forward_args = contract.forward_args(),
        svc_iface = format!("{}Service", table.struct_name),
        repo_iface = format!("{}Repository", table.struct_name),
        impl_type = impl_type(table, "Service"),
        fn = table.struct_name,
    );

    GeneratedFile {
        path: format!("internal/service/{}_service.go", table.file_base),
        content,
        table: table.sql_name.clone(),
        kind: FileKind::Service,
    }
}

/// Renders `internal/cache/<table>_cache.go`: a decorator that wraps the
/// repository interface, caching GetByID in Redis and invalidating on
/// Update/Delete. Cache errors degrade to DB (spec: 缓存契约).
fn cache(table: &Table, request: &GenerateRequest) -> GeneratedFile {
    let contract = Contract::new(table);

    // The key format is resolved once (ADR-0002); this layer only supplies the
    // argument expressions for GetByID/Delete (params) and Update (model
    // fields), so the written and invalidated keys cannot diverge.
    let key_format = table
        .cache_key_format
        .as_deref()
        .expect("cache rendering requires a primary key");
    let cache_key_expr = format!("fmt.Sprintf(\"{}\", {})", key_format, contract.get_args());
    let update_cache_key = format!("fmt.Sprintf(\"{}\", {})", key_format, contract.model_args());

    let content = format!(
        r#"// Code generated by gorm-generate. DO NOT EDIT.

package cache

import (
	"context"
	"encoding/json"
	"fmt"
	"time"

	"github.com/redis/go-redis/v9"

	"{module}/internal/model"
	"{module}/internal/repository"
)

const {const_name}CacheTTL = {ttl} * time.Second

// {impl_type} decorates {repo_iface}, caching GetByID in Redis.
// Cache errors degrade to the underlying repository; they are never
// propagated to the caller.
type {impl_type} struct {{
	repo repository.{repo_iface}
	rdb  *redis.Client
}}

// New{fn}RepoWithCache wraps a repository with a Redis cache decorator.
func New{fn}RepoWithCache(repo repository.{repo_iface}, rdb *redis.Client) repository.{repo_iface} {{
	return &{impl_type}{{repo: repo, rdb: rdb}}
}}

func (c *{impl_type}) {create} {{
	return c.repo.Create(ctx, m)
}}

func (c *{impl_type}) {get_by_id} {{
	key := {cache_key_expr}
	data, err := c.rdb.Get(ctx, key).Bytes()
	if err == nil {{
		var m {s}
		if json.Unmarshal(data, &m) == nil {{
			return &m, nil
		}}
	}}
	m, dbErr := c.repo.GetByID({forward_args})
	if dbErr != nil {{
		return nil, dbErr
	}}
	if encoded, err := json.Marshal(m); err == nil {{
		_ = c.rdb.Set(ctx, key, encoded, {const_name}CacheTTL).Err()
	}}
	return m, nil
}}

func (c *{impl_type}) {list} {{
	return c.repo.List(ctx, page, pageSize)
}}

func (c *{impl_type}) {update} {{
	err := c.repo.Update(ctx, m)
	if err == nil {{
		key := {update_cache_key}
		_ = c.rdb.Del(ctx, key).Err()
	}}
	return err
}}

func (c *{impl_type}) {delete} {{
	err := c.repo.Delete({forward_args})
	if err == nil {{
		key := {cache_key_expr}
		_ = c.rdb.Del(ctx, key).Err()
	}}
	return err
}}
"#,
        module = request.module_path,
        s = contract.model_type(),
        create = contract.signature(Method::Create),
        get_by_id = contract.signature(Method::GetByID),
        list = contract.signature(Method::List),
        update = contract.signature(Method::Update),
        delete = contract.signature(Method::Delete),
        forward_args = contract.forward_args(),
        cache_key_expr = cache_key_expr,
        update_cache_key = update_cache_key,
        ttl = request.cache_ttl_seconds,
        const_name = table.struct_name,
        repo_iface = format!("{}Repository", table.struct_name),
        impl_type = impl_type(table, "CacheRepo"),
        fn = table.struct_name,
    );

    GeneratedFile {
        path: format!("internal/cache/{}_cache.go", table.file_base),
        content,
        table: table.sql_name.clone(),
        kind: FileKind::Cache,
    }
}

/// Unexported impl type name: `users` -> `userRepository` (repo pkg) and
/// `userService` (service pkg). The two packages are separate, so the same
/// lowercase prefix can exist in each without collision.
fn impl_type(table: &Table, suffix: &str) -> String {
    format!("{}{}", table.impl_type_base, suffix)
}

fn where_chain(table: &Table, dialect: Dialect) -> String {
    let chain = table
        .pk()
        .map(|pk| format!("{} = ?", quote_sql(&pk.sql_name, dialect)))
        .collect::<Vec<_>>()
        .join(" AND ");
    go_string_literal(&chain)
}

/// Escapes text for use inside a Go string literal. Identifiers reaching
/// here are SQL names, so quotes are the only character that needs escaping.
fn go_string_literal(text: &str) -> String {
    text.replace('"', "\\\"")
}

fn quote_sql(name: &str, dialect: Dialect) -> String {
    match dialect {
        Dialect::MySql => format!("`{name}`"),
        Dialect::PostgreSql => format!("\"{name}\""),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser;
    use crate::resolve::resolve_table;

    fn request(ddl: &str) -> GenerateRequest {
        GenerateRequest {
            ddl: ddl.into(),
            dialect: Dialect::MySql,
            module_path: "example.com/app".into(),
            cache_enabled: true,
            cache_ttl_seconds: 300,
            tinyint_as_bool: false,
        }
    }

    #[test]
    fn table_owns_its_files_warnings_and_dependencies() {
        let ddl = "CREATE TABLE `users` (`id` BIGINT NOT NULL, PRIMARY KEY (`id`)); \
                   CREATE TABLE `logs` (`msg` TEXT NOT NULL);";
        let script = parser::parse_ddl(ddl, Dialect::MySql).expect("ddl should parse");
        let request = request(ddl);

        let users = table(&resolve_table(&script.tables[0], false), &request);
        let kinds: Vec<FileKind> = users.files.iter().map(|file| file.kind).collect();
        assert_eq!(
            kinds,
            [FileKind::Model, FileKind::Repository, FileKind::Service, FileKind::Cache]
        );
        assert_eq!(users.dependencies, [GORM, REDIS]);
        assert!(users.warnings.is_empty());

        // No primary key: one model, no third-party imports, and the rule is
        // visible here rather than only through `generate`.
        let logs = table(&resolve_table(&script.tables[1], false), &request);
        assert_eq!(logs.files.len(), 1);
        assert_eq!(logs.files[0].kind, FileKind::Model);
        assert!(logs.dependencies.is_empty());
        assert_eq!(logs.warnings.len(), 1);
        assert!(logs.warnings[0].contains("no primary key"), "{:?}", logs.warnings);
    }
}
