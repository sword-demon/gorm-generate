//! Repository and service layer rendering (spec: 仓储契约 / 服务契约).

use crate::generate::{GeneratedFile, GenerateRequest};
use crate::naming::{field_name, snake_case, struct_name};
use crate::parser::ParsedTable;

/// One primary key column: Go name (snake, as in DDL) and Go type.
pub struct PkColumn {
    pub name: String,
    pub go_type: String,
}

/// Extracts the primary key columns' Go types, following DDL types.
pub fn pk_columns(table: &ParsedTable, request: &GenerateRequest) -> Vec<PkColumn> {
    table
        .primary_key
        .iter()
        .filter_map(|pk| {
            let col = table.columns.iter().find(|c| c.name.value == *pk)?;
            let mapped =
                crate::types::column_type(col, false, request.tinyint_as_bool, true);
            Some(PkColumn {
                name: pk.clone(),
                go_type: mapped.go_type.trim_start_matches('*').to_string(),
            })
        })
        .collect()
}

/// Renders `internal/repository/<table>_repo.go`: interface, GORM impl, and
/// constructor in one file. Only called for tables with a primary key.
pub fn render_repository(
    table: &ParsedTable,
    request: &GenerateRequest,
) -> GeneratedFile {
    let struct_name = struct_name(&table.name);
    let file_base = snake_case(&struct_name);
    let pks = pk_columns(table, request);

    let get_params = params_list(&pks, "ctx context.Context, ");
    let where_chain = where_chain(&pks, request.dialect);

    let type_imports = if pks.iter().any(|p| p.go_type.contains("time.Time")) { "\t\"time\"\n" } else { "" };
    let json_import = if pks.iter().any(|p| p.go_type.contains("json.RawMessage")) { "\t\"encoding/json\"\n" } else { "" };
    let content = format!(
        r#"// Code generated by gorm-generate. DO NOT EDIT.

package repository

import (
	"context"
	"fmt"
{type_imports}{json_import}
	"gorm.io/gorm"

	"{module}/internal/model"
)

// {repo_iface} is the persistence boundary for the {table} table.
type {repo_iface} interface {{
	Create(ctx context.Context, m *{s}) error
	GetByID({get_params}) (*{s}, error)
	List(ctx context.Context, page int, pageSize int) ([]*{s}, int64, error)
	Update(ctx context.Context, m *{s}) error
	Delete({get_params}) error
}}

// {impl_type} implements {repo_iface} with GORM.
type {impl_type} struct {{
	db *gorm.DB
}}

// New{fn}Repository builds the GORM-backed implementation.
func New{fn}Repository(db *gorm.DB) {repo_iface} {{
	return &{impl_type}{{db: db}}
}}

func (r *{impl_type}) Create(ctx context.Context, m *{s}) error {{
	return r.db.WithContext(ctx).Create(m).Error
}}

func (r *{impl_type}) GetByID({get_params}) (*{s}, error) {{
	var m {s}
	err := r.db.WithContext(ctx).Where("{where_chain}", {where_args}).First(&m).Error
	if err != nil {{
		return nil, err
	}}
	return &m, nil
}}

func (r *{impl_type}) List(ctx context.Context, page int, pageSize int) ([]*{s}, int64, error) {{
	if page < 1 || pageSize < 1 || page - 1 > int(^uint(0) >> 1) / pageSize {{
		return nil, 0, fmt.Errorf("page and pageSize must be positive and offset must fit int")
	}}
	var total int64
	if err := r.db.WithContext(ctx).Model(&{s}{{}}).Count(&total).Error; err != nil {{
		return nil, 0, err
	}}
	var items []*{s}
	offset := (page - 1) * pageSize
	err := r.db.WithContext(ctx).Order("{order}").Offset(offset).Limit(pageSize).Find(&items).Error
	return items, total, err
}}

func (r *{impl_type}) Update(ctx context.Context, m *{s}) error {{
	return r.db.WithContext(ctx).Save(m).Error
}}

func (r *{impl_type}) Delete({get_params}) error {{
	return r.db.WithContext(ctx).Where("{where_chain}", {where_args}).Delete(&{s}{{}}).Error
}}
"#,
        type_imports = type_imports,
        json_import = json_import,
        module = request.module_path,
        table = table.name,
        s = format!("model.{struct_name}"),
        get_params = get_params,
        where_chain = where_chain,
        where_args = where_args(&pks),
        order = pks.iter().map(|p| quote_sql(&p.name, request.dialect)).collect::<Vec<_>>().join(",").replace('"', "\\\""),
        repo_iface = format!("{struct_name}Repository"),
        impl_type = impl_type_name(&struct_name, "Repository"),
        fn = struct_name,
    );

    GeneratedFile {
        path: format!("internal/repository/{}_repo.go", file_base),
        content,
        table: table.name.clone(),
    }
}

/// Renders `internal/service/<table>_service.go`: interface, thin passthrough
/// impl, and constructor injecting the repository interface.
pub fn render_service(
    table: &ParsedTable,
    request: &GenerateRequest,
) -> GeneratedFile {
    let struct_name = struct_name(&table.name);
    let file_base = snake_case(&struct_name);
    let pks = pk_columns(table, request);
    let get_params = params_list(&pks, "ctx context.Context, ");

    let type_imports = if pks.iter().any(|p| p.go_type.contains("time.Time")) { "\t\"time\"\n" } else { "" };
    let json_import = if pks.iter().any(|p| p.go_type.contains("json.RawMessage")) { "\t\"encoding/json\"\n" } else { "" };
    let content = format!(
        r#"// Code generated by gorm-generate. DO NOT EDIT.

package service

import (
	"context"
{type_imports}{json_import}
	"{module}/internal/model"
	"{module}/internal/repository"
)

// {svc_iface} is the business-layer boundary for the {table} table. Fill in
// real business rules; the generated methods are thin passthroughs.
type {svc_iface} interface {{
	Create(ctx context.Context, m *{s}) error
	GetByID({get_params}) (*{s}, error)
	List(ctx context.Context, page int, pageSize int) ([]*{s}, int64, error)
	Update(ctx context.Context, m *{s}) error
	Delete({get_params}) error
}}

type {impl_type} struct {{
	repo repository.{repo_iface}
}}

// New{fn}Service injects the repository interface; wire either the plain
// GORM repo or a cache decorator at the callsite.
func New{fn}Service(repo repository.{repo_iface}) {svc_iface} {{
	return &{impl_type}{{repo: repo}}
}}

func (s *{impl_type}) Create(ctx context.Context, m *{s}) error {{
	return s.repo.Create(ctx, m)
}}

func (s *{impl_type}) GetByID({get_params}) (*{s}, error) {{
	return s.repo.GetByID({get_args_for_service})
}}

func (s *{impl_type}) List(ctx context.Context, page int, pageSize int) ([]*{s}, int64, error) {{
	return s.repo.List(ctx, page, pageSize)
}}

func (s *{impl_type}) Update(ctx context.Context, m *{s}) error {{
	return s.repo.Update(ctx, m)
}}

func (s *{impl_type}) Delete({get_params}) error {{
	return s.repo.Delete({get_args_for_service})
}}
"#,
        type_imports = type_imports,
        json_import = json_import,
        module = request.module_path,
        table = table.name,
        s = format!("model.{struct_name}"),
        get_params = get_params,
        get_args_for_service = service_get_args(&pks),
        svc_iface = format!("{struct_name}Service"),
        repo_iface = format!("{struct_name}Repository"),
        impl_type = impl_type_name(&struct_name, "Service"),
        fn = struct_name,
    );

    GeneratedFile {
        path: format!("internal/service/{}_service.go", file_base),
        content,
        table: table.name.clone(),
    }
}

fn params_list(pks: &[PkColumn], prefix: &str) -> String {
    let mut parts: Vec<String> = Vec::new();
    for pk in pks {
        parts.push(format!("{} {}", param_name(&pk.name), pk.go_type));
    }
    format!("{prefix}{}", parts.join(", "))
}

fn args_list(pks: &[PkColumn]) -> String {
    pks.iter().map(|p| param_name(&p.name)).collect::<Vec<_>>().join(", ")
}

/// The Where clause's placeholder arguments: the Go parameter names.
fn where_args(pks: &[PkColumn]) -> String {
    args_list(pks)
}

/// Unexported impl type name: `users` -> `userRepository` (repo pkg) and
/// `userService` (service pkg). The two packages are separate, so the same
/// lowercase prefix can exist in each without collision.
fn impl_type_name(struct_name: &str, suffix: &str) -> String {
    format!("{}{}", struct_name.to_lowercase(), suffix)
}

/// Service passthrough forwards ctx + PK args verbatim.
fn service_get_args(pks: &[PkColumn]) -> String {
    format!("ctx, {}", args_list(pks))
}

/// Renders `internal/cache/<table>_cache.go`: a decorator that wraps the
/// repository interface, caching GetByID in Redis and invalidating on
/// Update/Delete. Cache errors degrade to DB (spec: 缓存契约).
pub fn render_cache(
    table: &ParsedTable,
    request: &GenerateRequest,
) -> GeneratedFile {
    let struct_name = struct_name(&table.name);
    let file_base = snake_case(&struct_name);
    let pks = pk_columns(table, request);
    let get_params = params_list(&pks, "ctx context.Context, ");

    // Cache key: "tablename:pk1:pk2" — composite PKs joined with `:`.
    let cache_key_expr = cache_key_expr(&table.name, &pks);

    let content = format!(
        r#"// Code generated by gorm-generate. DO NOT EDIT.

package cache

import (
	"context"
	"encoding/json"
	"fmt"
	"time"

	"github.com/redis/go-redis/v9"

	"{module}/internal/model"
	"{module}/internal/repository"
)

const {const_name}CacheTTL = {ttl} * time.Second

// {impl_type} decorates {repo_iface}, caching GetByID in Redis.
// Cache errors degrade to the underlying repository; they are never
// propagated to the caller.
type {impl_type} struct {{
	repo repository.{repo_iface}
	rdb  *redis.Client
}}

// New{fn}RepoWithCache wraps a repository with a Redis cache decorator.
func New{fn}RepoWithCache(repo repository.{repo_iface}, rdb *redis.Client) repository.{repo_iface} {{
	return &{impl_type}{{repo: repo, rdb: rdb}}
}}

func (c *{impl_type}) Create(ctx context.Context, m *{s}) error {{
	return c.repo.Create(ctx, m)
}}

func (c *{impl_type}) GetByID({get_params}) (*{s}, error) {{
	key := {cache_key_expr}
	data, err := c.rdb.Get(ctx, key).Bytes()
	if err == nil {{
		var m {s}
		if json.Unmarshal(data, &m) == nil {{
			return &m, nil
		}}
	}}
	m, dbErr := c.repo.GetByID({get_args_for_cache})
	if dbErr != nil {{
		return nil, dbErr
	}}
	if encoded, err := json.Marshal(m); err == nil {{
		_ = c.rdb.Set(ctx, key, encoded, {const_name}CacheTTL).Err()
	}}
	return m, nil
}}

func (c *{impl_type}) List(ctx context.Context, page int, pageSize int) ([]*{s}, int64, error) {{
	return c.repo.List(ctx, page, pageSize)
}}

func (c *{impl_type}) Update(ctx context.Context, m *{s}) error {{
	err := c.repo.Update(ctx, m)
	if err == nil {{
		key := {update_cache_key}
		_ = c.rdb.Del(ctx, key).Err()
	}}
	return err
}}

func (c *{impl_type}) Delete({get_params}) error {{
	err := c.repo.Delete({get_args_for_cache})
	if err == nil {{
		key := {cache_key_expr}
		_ = c.rdb.Del(ctx, key).Err()
	}}
	return err
}}
"#,
        module = request.module_path,
        s = format!("model.{struct_name}"),
        get_params = get_params,
        cache_key_expr = cache_key_expr,
        get_args_for_cache = service_get_args(&pks),
        update_cache_key = update_cache_key_expr(&table.name, &pks),
        ttl = request.cache_ttl_seconds,
        const_name = struct_name,
        repo_iface = format!("{struct_name}Repository"),
        impl_type = impl_type_name(&struct_name, "CacheRepo"),
        fn = struct_name,
    );

    GeneratedFile {
        path: format!("internal/cache/{}_cache.go", file_base),
        content,
        table: table.name.clone(),
    }
}

/// Cache key expression: `fmt.Sprintf("tablename:%v", id)` for single PK,
/// `fmt.Sprintf("tablename:%v:%v", orderId, itemId)` for composite.
fn cache_key_expr(table_name: &str, pks: &[PkColumn]) -> String {
    let format_str = format!(
        "{}:{}",
        table_name,
        pks.iter().map(|_| "%v").collect::<Vec<_>>().join(":")
    );
    let args = pks
        .iter()
        .map(|p| param_name(&p.name))
        .collect::<Vec<_>>()
        .join(", ");
    format!("fmt.Sprintf(\"{format_str}\", {args})")
}

/// Update needs to extract PK values from the model struct to build the
/// cache key. Uses `m.FieldName` for each PK column.
fn update_cache_key_expr(table_name: &str, pks: &[PkColumn]) -> String {
    let format_str = format!(
        "{}:{}",
        table_name,
        pks.iter().map(|_| "%v").collect::<Vec<_>>().join(":")
    );
    let args = pks
        .iter()
        .map(|p| format!("m.{}", field_name(&p.name)))
        .collect::<Vec<_>>()
        .join(", ");
    format!("fmt.Sprintf(\"{format_str}\", {args})")
}

fn where_chain(pks: &[PkColumn], dialect: crate::generate::Dialect) -> String {
    pks.iter()
        .map(|p| format!("{} = ?", quote_sql(&p.name, dialect)))
        .collect::<Vec<_>>()
        .join(" AND ").replace('"', "\\\"")
}

/// Go-idiomatic parameter names for PK columns: `user_id` -> `userId`.
pub fn param_name(column: &str) -> String {
    let field = field_name(column);
    if field.is_empty() {
        return column.to_string();
    }
    let mut out = String::new();
    for (i, c) in field.chars().enumerate() {
        if i == 0 {
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    // An all-caps DDL identifier (`"ID"`, `"URL"`) is an initialism: Go style
    // wants `id`, not `iD`.
    if !field.chars().any(|c| c.is_lowercase()) {
        out = field.to_lowercase();
    }
    match out.as_str() {
        "break" | "default" | "func" | "interface" | "select" | "case" | "defer" | "go" | "map" | "struct" | "chan" | "else" | "goto" | "package" | "switch" | "const" | "fallthrough" | "if" | "range" | "type" | "continue" | "for" | "import" | "return" | "var" | "ctx" | "r" | "s" | "c" | "m" | "err" | "key" | "data" | "dbErr" | "encoded" | "fmt" | "time" | "json" | "model" | "repository" | "redis" | "context" => format!("{out}PK"),
        _ => out,
    }
}

fn quote_sql(name: &str, dialect: crate::generate::Dialect) -> String {
    match dialect {
        crate::generate::Dialect::MySql => format!("`{name}`"),
        crate::generate::Dialect::PostgreSql => format!("\"{name}\""),
    }
}
